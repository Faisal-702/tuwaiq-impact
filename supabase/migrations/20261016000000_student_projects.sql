-- Student "My Projects": persistent student profile, several supervisors per
-- project, manually recorded funding support, a student activity history and
-- editing of submitted projects.
--
-- Additive, backward compatible and idempotent (safe to run more than once,
-- and safe to paste into the Supabase SQL editor on its own). No table is
-- dropped, no existing row is deleted. The only existing objects changed:
--  * projects gains one nullable column (supervisors), back-filled from the
--    single supervisor already on record;
--  * project_submissions' status check is widened to also allow 'editing'
--    (a student's pending changes to a submitted project).
--
-- Ownership: a student owns a project when their submitted questionnaire
-- (project_submissions, written with the student session's id) points at it.
-- Nothing here guesses ownership from names.
--
-- Access model unchanged: RLS enabled with no policies for the public API
-- roles and their grants revoked; only the server reads and writes, after
-- checking the student or admin session.

-- ---------------------------------------------------------------------------
-- 1. Student profile (private; pre-fills the first step of the project form)
-- ---------------------------------------------------------------------------

create table if not exists public.student_profiles (
  student_id uuid primary key references public.students (id) on delete cascade,
  full_name text check (full_name is null or char_length(full_name) between 1 and 120),
  -- Saudi national ID / Iqama, normalised to 10 digits.
  national_id text check (national_id is null or national_id ~ '^[12][0-9]{9}$'),
  -- Saudi mobile, normalised to 05XXXXXXXX.
  phone text check (phone is null or phone ~ '^05[0-9]{8}$'),
  email text check (email is null or (char_length(email) between 5 and 254 and position('@' in email) > 1)),
  grade smallint check (grade is null or grade in (10, 11, 12)),
  section smallint check (section is null or section between 1 and 3),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists student_profiles_touch on public.student_profiles;
create trigger student_profiles_touch before update on public.student_profiles
  for each row execute function public.ti_touch_updated_at();

-- ---------------------------------------------------------------------------
-- 2. Several supervisors / teachers per project
-- ---------------------------------------------------------------------------
-- Private, like the questionnaire it comes from: shown only to the project's
-- own student (My Projects, editing) and to administrators. Public pages keep
-- showing only projects.supervisor, which administrators set themselves.

alter table public.projects add column if not exists supervisors text[];

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'projects_supervisors_size') then
    alter table public.projects
      add constraint projects_supervisors_size check (supervisors is null or cardinality(supervisors) <= 20);
  end if;
end
$$;

-- Back-fill (only where the new column is still empty): the supervisor the
-- student gave on the submission form, else the single admin-entered one.
update public.projects p
   set supervisors = array[left(trim(ps.answers->>'supervisor'), 120)]
  from public.project_submissions ps
 where ps.project_id = p.id
   and ps.status = 'submitted'
   and p.supervisors is null
   and coalesce(trim(ps.answers->>'supervisor'), '') <> '';

update public.projects
   set supervisors = array[left(trim(supervisor), 120)]
 where supervisors is null
   and coalesce(trim(supervisor), '') <> '';

-- ---------------------------------------------------------------------------
-- 3. Funding support recorded manually by the student
-- ---------------------------------------------------------------------------
-- Not a payment system: each row is an amount the student reports having
-- received. Totals are always computed from these rows (never stored). A
-- mistaken entry is reversed (kept, marked with who/when/why), never edited
-- or deleted.

create table if not exists public.project_support_entries (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  amount numeric(12, 2) not null check (amount > 0 and amount <= 10000000),
  note text check (note is null or char_length(note) <= 200),
  recorded_by text not null default 'student' check (recorded_by in ('student', 'admin')),
  recorded_by_student_id uuid references public.students (id) on delete set null,
  -- Random id generated by the form: a retried or double-clicked submission
  -- is stored once.
  client_token uuid not null,
  created_at timestamptz not null default now(),
  reversed_at timestamptz,
  reversed_by_student_id uuid references public.students (id) on delete set null,
  reversal_reason text check (reversal_reason is null or char_length(reversal_reason) <= 200),
  constraint project_support_entries_reversal check (reversed_at is not null or reversal_reason is null)
);

create unique index if not exists project_support_entries_token_key on public.project_support_entries (client_token);
create index if not exists project_support_entries_project_idx on public.project_support_entries (project_id, created_at desc);

-- ---------------------------------------------------------------------------
-- 4. Student activity history (what the student did on their projects)
-- ---------------------------------------------------------------------------
-- Only kinds, field keys and amounts: never personal data. "Project created"
-- comes from project_submissions.submitted_at and is not stored here.

create table if not exists public.student_project_activity (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students (id) on delete cascade,
  project_id uuid references public.projects (id) on delete cascade,
  kind text not null check (kind in ('edited', 'cover_changed', 'support_added', 'support_reversed')),
  amount numeric(12, 2),
  fields text[],
  created_at timestamptz not null default now()
);

create index if not exists student_project_activity_student_idx on public.student_project_activity (student_id, created_at desc);

-- ---------------------------------------------------------------------------
-- 5. Editing a submitted project: the student's pending changes
-- ---------------------------------------------------------------------------

alter table public.project_submissions drop constraint if exists project_submissions_status_check;
alter table public.project_submissions
  add constraint project_submissions_status_check check (status in ('draft', 'submitted', 'editing'));

-- One pending edit per student and project.
create unique index if not exists project_submissions_one_edit
  on public.project_submissions (student_id, project_id) where status = 'editing';

-- Faster ownership checks.
create index if not exists project_submissions_owner_idx
  on public.project_submissions (student_id, project_id) where status = 'submitted';

-- ---------------------------------------------------------------------------
-- Access: server only
-- ---------------------------------------------------------------------------

alter table public.student_profiles enable row level security;
alter table public.project_support_entries enable row level security;
alter table public.student_project_activity enable row level security;

do $$
declare
  t text;
begin
  foreach t in array array['student_profiles', 'project_support_entries', 'student_project_activity'] loop
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on table public.%I from anon', t);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on table public.%I from authenticated', t);
    end if;
  end loop;
end
$$;
