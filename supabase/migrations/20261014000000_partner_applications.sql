-- Partnership applications submitted through the public "Partners" form on
-- the landing page (individuals and organisations who want to support the
-- students and their projects).
--
-- Additive and idempotent: creates one new table only; no existing table or
-- data is touched. Safe to run more than once.
--
-- Access model (same as the rest of the schema):
--  * Visitors submit through a validated server action that inserts with the
--    server's privileged connection (rate-limited, duplicate-protected).
--  * Row Level Security is enabled with NO policies for the public API roles,
--    and their grants are revoked: the Supabase anon/authenticated keys can
--    neither read nor write this table directly (no public listing, no direct
--    inserts that would bypass server-side validation).
--  * Only the admin dashboard (server-side, admin session required) reads it.
--
-- There is deliberately no status column: the admin page lists and shows the
-- applications; it has no approval/rejection workflow.

create table if not exists public.partner_applications (
  id uuid primary key default gen_random_uuid(),
  partner_type text not null check (partner_type in ('individual', 'organization')),
  full_name text not null check (char_length(trim(full_name)) between 2 and 120),
  -- Organisation details: required for organisations, absent for individuals.
  organization_name text check (organization_name is null or char_length(trim(organization_name)) between 2 and 160),
  organization_category text check (
    organization_category is null
    or organization_category in ('private', 'government', 'nonprofit', 'education', 'other')
  ),
  job_title text check (job_title is null or char_length(trim(job_title)) between 2 and 120),
  -- Saudi mobile, normalised to 05XXXXXXXX by the server.
  phone text not null check (phone ~ '^05[0-9]{8}$'),
  email text not null check (char_length(email) between 5 and 254 and position('@' in email) > 1),
  city text not null check (char_length(trim(city)) between 2 and 80),
  support_types text[] not null check (
    cardinality(support_types) between 1 and 6
    and support_types <@ array['financial', 'technical', 'mentorship', 'training', 'sponsorship', 'other']::text[]
  ),
  interest_fields text[] not null check (
    cardinality(interest_fields) between 1 and 7
    and interest_fields <@ array['all', 'ai', 'robotics', 'cybersecurity', 'programming', 'research', 'other']::text[]
  ),
  proposal text not null check (char_length(trim(proposal)) between 10 and 2000),
  -- When the applicant accepted the privacy notice (required to submit).
  consent_at timestamptz not null,
  -- Language the form was filled in (for the admin's context only).
  locale text not null default 'ar' check (locale in ('ar', 'en')),
  -- Random token generated by the form: a retried or double-clicked submit
  -- stores the application once.
  client_token uuid not null,
  -- Salted hash of the visitor's network address, used only for rate limiting
  -- (the address itself is never stored).
  ip_hash text not null,
  created_at timestamptz not null default now(),
  constraint partner_applications_org_fields check (
    (partner_type = 'individual' and organization_name is null and organization_category is null and job_title is null)
    or (partner_type = 'organization' and organization_name is not null and organization_category is not null and job_title is not null)
  )
);

create unique index if not exists partner_applications_client_token_key on public.partner_applications (client_token);
create index if not exists partner_applications_created_idx on public.partner_applications (created_at desc, id desc);
create index if not exists partner_applications_ip_created_idx on public.partner_applications (ip_hash, created_at desc);
create index if not exists partner_applications_email_idx on public.partner_applications (lower(email), created_at desc);

alter table public.partner_applications enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on table public.partner_applications from anon;
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on table public.partner_applications from authenticated;
  end if;
end
$$;
